use crate::utils::{alter_table_cmds, cmd_def};
use crate::{LinterDiagnostic, LinterRule, LinterRuleContext};
use pgls_analyse::{RuleSource, declare_lint_rule};
use pgls_console::markup;
use pgls_diagnostics::Severity;
use pgls_query::protobuf::{AlterTableCmd, AlterTableType};

/// `ATTRIBUTE_IDENTITY_ALWAYS`, how Postgres encodes `GENERATED ALWAYS`.
const IDENTITY_ALWAYS: u8 = b'a';

declare_lint_rule! {
    /// Changing the identity of a column may break inserts from existing clients.
    ///
    /// Inserts that provide an explicit value fail with `428C9 generated_always` once the column
    /// is `GENERATED ALWAYS`, and inserts that omit the column fail once its identity is dropped.
    ///
    /// Adding or switching to `GENERATED BY DEFAULT` keeps both kinds of inserts working, so it
    /// is not reported.
    ///
    /// ## Examples
    ///
    /// ### Invalid
    ///
    /// ```sql,expect_diagnostic
    /// alter table users alter column id add generated always as identity;
    /// ```
    ///
    /// ```sql,expect_diagnostic
    /// alter table users alter column id drop identity;
    /// ```
    ///
    /// ```sql,expect_diagnostic
    /// alter table users alter column id set generated always;
    /// ```
    ///
    /// ### Valid
    ///
    /// ```sql
    /// alter table users alter column id add generated by default as identity;
    /// ```
    ///
    pub BanAlterIdentity {
        version: "next",
        name: "banAlterIdentity",
        severity: Severity::Warning,
        recommended: false,
        applies_to: pgls_analyse::AppliesTo::Migration,
        sources: &[RuleSource::Squawk("ban-alter-identity")],
    }
}

impl LinterRule for BanAlterIdentity {
    type Options = ();

    fn run(ctx: &LinterRuleContext<Self>) -> Vec<LinterDiagnostic> {
        alter_table_cmds(ctx.stmt())
            .filter_map(breaking_change)
            .map(|(column, detail)| {
                LinterDiagnostic::new(
                    rule_category!(),
                    None,
                    markup! {
                        "Changing the identity of column "<Emphasis>{column}</Emphasis>" may break inserts from existing clients."
                    },
                )
                .detail(None, detail)
                .note("Update client inserts before changing the identity.")
            })
            .collect()
    }
}

fn breaking_change(cmd: &AlterTableCmd) -> Option<(&str, &'static str)> {
    let always = "Inserts that provide an explicit value fail once the column is GENERATED ALWAYS.";
    match cmd.subtype() {
        AlterTableType::AtAddIdentity => match cmd_def(cmd)? {
            pgls_query::NodeEnum::Constraint(constraint)
                if constraint.generated_when.as_bytes() == [IDENTITY_ALWAYS] =>
            {
                Some((&cmd.name, always))
            }
            _ => None,
        },
        AlterTableType::AtDropIdentity => Some((
            &cmd.name,
            "Inserts that omit the column fail once it no longer generates values.",
        )),
        AlterTableType::AtSetIdentity => {
            let pgls_query::NodeEnum::List(options) = cmd_def(cmd)? else {
                return None;
            };
            options
                .items
                .iter()
                .any(|option| match &option.node {
                    Some(pgls_query::NodeEnum::DefElem(option))
                        if option.defname == "generated" =>
                    {
                        matches!(
                            option.arg.as_ref().and_then(|arg| arg.node.as_ref()),
                            Some(pgls_query::NodeEnum::Integer(value))
                                if value.ival == i32::from(IDENTITY_ALWAYS)
                        )
                    }
                    _ => false,
                })
                .then_some((&cmd.name, always))
        }
        _ => None,
    }
}
