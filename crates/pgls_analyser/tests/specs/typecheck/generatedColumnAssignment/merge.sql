create table items (
  price int,
  quantity int,
  total int generated always as (price * quantity) stored
);
create table users (
  id int generated always as identity primary key,
  legacy_id int generated by default as identity,
  name text
);
create table source (id int, price int, name text);
merge into items i using source s on s.price = i.price
  when matched then update set quantity = 2, total = default
  when not matched then insert (price, total) values (s.price, default);
merge into users u using source s on s.id = u.id
  when matched then update set legacy_id = 1, id = default
  when not matched then insert default values;
merge into users u using source s on s.id = u.id
  when not matched then insert (id, name) values (default, s.name);
